// ===========================================================================
// Generate migration 0106 — the catalogue refresh of 2026-10-27 (D223).
//
//   npx ts-node scripts/generate-catalogue-refresh-migration.ts
//
// Inserts exactly the rows `src/catalog/catalogue-refresh.ts` names, each read
// from the manufacturer's own pages, and re-ranks the brands they joined.
// `0062` and `0063` are immutable history and are not touched.
//
// Idempotent by construction: every insert is `NOT EXISTS` (never IGNORE or
// REPLACE), and every UPDATE is keyed on (brand, name) and sets one column to
// a constant, so a second run changes nothing.
// ===========================================================================

import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BRANDS, MODELS, normaliseSearch, searchTermsFor } from '../src/catalog/device-catalogue';
import { PROVENANCE, REFRESH_BRANDS, REFRESH_REVIEWED_ON } from '../src/catalog/catalogue-refresh';

const DIR = join(__dirname, '..', 'prisma', 'migrations', '0106_device_catalogue_refresh');

/** MySQL string literal. Single quotes doubled; nothing else needs escaping here. */
const q = (v: string) => `'${v.replace(/'/g, "''")}'`;

const HEADER = `-- ===========================================================================
-- 0106 — device catalogue refresh, 2026-10-27 (D223).
--
-- Generated by scripts/generate-catalogue-refresh-migration.ts from
-- src/catalog/catalogue-refresh.ts. Do not edit by hand.
--
-- What it adds
-- ------------
-- Brands: Google Pixel, OnePlus, Motorola, HMD. Models: each one listed under
-- that exact name on the manufacturer's own site and dated by a page of the
-- manufacturer's — iPhone Duo, iPhone 18 Pro Max and iPhone 18 Pro among them.
-- The provenance of every row, and what was checked and NOT added (no plain
-- "iPhone 18" is listed by Apple), is in catalogue-refresh.ts.
--
-- No rumour, leak, retailer name or expected model. No TAC range, IMEI,
-- storage variant, colour or specification. Rows are 'curated' (hand-read
-- from official pages), never 'official', which is reserved for a licensed
-- feed.
--
-- Semantics
-- ---------
--   * inserts only rows that do not exist (NOT EXISTS on the natural key);
--   * re-ranks the brands that gained models, keyed on (brand, name);
--   * renames, deletes and deactivates nothing; no product is touched;
--   * a second run changes nothing.
--
-- Reverse: DELETE the models named below by (brand_key, name), then the four
-- brands, then run 0063's UPDATEs for Apple again.
-- ===========================================================================
`;

export function buildRefreshSql(): string {
  const lines: string[] = [HEADER];

  lines.push('\n-- Brands.\n');
  for (const key of REFRESH_BRANDS) {
    const b = BRANDS.find((brand) => brand.key === key)!;
    const terms = normaliseSearch([b.name, b.key, ...b.aliases].join(' '));
    lines.push(
      `INSERT INTO \`device_brands\` (\`key\`,\`name\`,\`search_terms\`,\`display_order\`,\`parent_key\`,\`is_active\`,\`source\`,\`reviewed_on\`)\n` +
        `SELECT ${q(b.key)},${q(b.name)},${q(terms)},${b.order},${b.parentKey ? q(b.parentKey) : 'NULL'},1,'curated',${q(REFRESH_REVIEWED_ON)}\n` +
        `WHERE NOT EXISTS (SELECT 1 FROM \`device_brands\` WHERE \`key\` = ${q(b.key)});`,
    );
  }

  lines.push('\n-- Models, each read from the manufacturer (see catalogue-refresh.ts).\n');
  for (const p of PROVENANCE) {
    const m = MODELS.find((model) => model.brandKey === p.brandKey && model.name === p.name)!;
    lines.push(
      `INSERT INTO \`device_models\` (\`brand_key\`,\`name\`,\`family\`,\`release_rank\`,\`display_rank\`,\`search_terms\`,\`is_active\`,\`source\`,\`reviewed_on\`)\n` +
        `SELECT ${q(m.brandKey)},${q(m.name)},${q(m.family)},${m.releaseRank},${m.displayRank},${q(searchTermsFor(m))},1,'curated',${q(REFRESH_REVIEWED_ON)}\n` +
        `WHERE NOT EXISTS (SELECT 1 FROM \`device_models\` WHERE \`brand_key\` = ${q(m.brandKey)} AND \`name\` = ${q(m.name)});`,
    );
  }

  /*
   * A brand that already existed and gained models has every row's position
   * moved; the new brands were inserted at their final ranks above.
   */
  const reranked = [...new Set(PROVENANCE.map((p) => p.brandKey))].filter(
    (key) => !(REFRESH_BRANDS as readonly string[]).includes(key),
  );
  lines.push('\n-- Display order of the existing brands that gained models.\n');
  for (const m of MODELS.filter((model) => reranked.includes(model.brandKey))) {
    lines.push(
      `UPDATE \`device_models\` SET \`display_rank\` = ${m.displayRank} WHERE \`brand_key\` = ${q(m.brandKey)} AND \`name\` = ${q(m.name)};`,
    );
  }

  return lines.join('\n') + '\n';
}

if (require.main === module) {
  mkdirSync(DIR, { recursive: true });
  writeFileSync(join(DIR, 'migration.sql'), buildRefreshSql(), 'utf8');
  console.log(`0106 written: ${REFRESH_BRANDS.length} brands, ${PROVENANCE.length} models, reviewed ${REFRESH_REVIEWED_ON}`);
}
