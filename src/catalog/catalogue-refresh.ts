/**
 * The catalogue refresh of 2026-10-27 (D223): what was added, where each row
 * was read, and what was checked and deliberately NOT added.
 *
 * ## The rule this file enforces
 *
 * A row is added only when the manufacturer's own site lists it under that
 * exact name AND a page of the manufacturer's dates its release year. No
 * rumour, leak, retailer listing or expected model; no TAC range, IMEI,
 * storage variant, colour or specification is added with any of them. Where
 * the name is official but no official page dates it, the model is recorded
 * below as checked and not added, rather than given a guessed year.
 *
 * The rows are still `curated`, not `official`: `official` is reserved for a
 * licensed feed (see `device-catalogue.ts`). These are hand-read from official
 * pages, which is exactly what `curated` means here.
 *
 * Migration `0106` inserts the added rows (generated by
 * `scripts/generate-catalogue-refresh-migration.ts`); the drift spec fails if
 * this file, the catalogue and the migration disagree. Re-running the
 * migration adds nothing.
 *
 * A future weekly agent may PROPOSE rows in this same shape. It must never
 * publish an unverified model to production by itself.
 */

export const REFRESH_REVIEWED_ON = '2026-10-27';

export interface ProvenanceEntry {
  brandKey: string;
  name: string;
  /** The manufacturer page that lists the model under this name. */
  listedAt: string;
  /** The manufacturer page that dates its release (the year in `releaseRank`). */
  datedBy: string;
  /** What that page says, briefly. */
  evidence: string;
}

export interface CheckedNotAdded {
  brandKey: string;
  name: string;
  reason: string;
  checkedAt: string;
}

